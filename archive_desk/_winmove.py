"""Win32 handles keep the checked file and directory entries stable until rename."""

import ctypes
from ctypes import wintypes
import msvcrt
import os
import struct
from contextlib import contextmanager
from pathlib import Path


kernel = ctypes.WinDLL("kernel32", use_last_error=True)
create_file = kernel.CreateFileW
create_file.argtypes = (
    wintypes.LPCWSTR, wintypes.DWORD, wintypes.DWORD, wintypes.LPVOID,
    wintypes.DWORD, wintypes.DWORD, wintypes.HANDLE,
)
create_file.restype = wintypes.HANDLE
set_information = kernel.SetFileInformationByHandle
set_information.argtypes = (wintypes.HANDLE, ctypes.c_int, wintypes.LPVOID, wintypes.DWORD)
set_information.restype = wintypes.BOOL
close_handle = kernel.CloseHandle
close_handle.argtypes = (wintypes.HANDLE,)
close_handle.restype = wintypes.BOOL

READ_ATTRIBUTES = 0x80
GENERIC_READ = 0x80000000
DELETE_ACCESS = 0x10000
SHARE_READ = 0x1
OPEN_EXISTING = 3
OPEN_REPARSE_POINT = 0x00200000
BACKUP_SEMANTICS = 0x02000000
INVALID_HANDLE = ctypes.c_void_p(-1).value


def extended_path(path: Path) -> str:
    plain = str(path)
    if plain.startswith("\\\\?\\"):
        return plain
    if plain.startswith("\\\\"):
        return "\\\\?\\UNC\\" + plain[2:]
    return "\\\\?\\" + plain


def open_entry(path: Path, access: int) -> int:
    handle = create_file(extended_path(path), access, SHARE_READ, None, OPEN_EXISTING,
                         OPEN_REPARSE_POINT | BACKUP_SEMANTICS, None)
    if handle == INVALID_HANDLE:
        raise ctypes.WinError(ctypes.get_last_error())
    return handle


@contextmanager
def pin_directory(path: Path):
    handle = open_entry(path, READ_ATTRIBUTES)
    try:
        info = path.lstat()
        if not info.st_file_attributes & 0x10 or info.st_file_attributes & 0x400:
            raise ValueError(f"目录已被替换，或为链接 / 重解析点：{path}")
        yield info.st_dev, info.st_ino
    finally:
        close_handle(handle)


@contextmanager
def open_regular(path: Path, access: int = GENERIC_READ):
    handle = open_entry(path, access)
    try:
        fd = msvcrt.open_osfhandle(handle, os.O_RDONLY | os.O_BINARY)
    except BaseException:
        close_handle(handle)
        raise
    with os.fdopen(fd, "rb") as stream:
        info = os.fstat(fd)
        if info.st_file_attributes & (0x10 | 0x400):
            raise ValueError("文件已被替换为目录、链接或其他重解析点")
        yield stream, handle, info


def open_for_move(path: Path):
    return open_regular(path, GENERIC_READ | DELETE_ACCESS)


@contextmanager
def open_staging(path, *, create):
    # CREATE_NEW never adopts an existing staging file. Resumes use OPEN_EXISTING
    # without truncation and check its recorded identity and prefix before writing.
    handle = create_file(extended_path(path), GENERIC_READ | 0x40000000 | DELETE_ACCESS,
                         SHARE_READ, None, 1 if create else OPEN_EXISTING, OPEN_REPARSE_POINT, None)
    if handle == INVALID_HANDLE:
        raise ctypes.WinError(ctypes.get_last_error())
    try:
        fd = msvcrt.open_osfhandle(handle, os.O_RDWR | os.O_BINARY)
    except BaseException:
        close_handle(handle)
        raise
    with os.fdopen(fd, "r+b", buffering=0) as stream:
        info = os.fstat(fd)
        if info.st_file_attributes & (0x10 | 0x400):
            raise ValueError("临时文件被替换为重解析点或目录")
        yield stream, handle, info


def cross_copy_supported(handle, info):
    if info.st_file_attributes & ~(0x20 | 0x80) or info.st_nlink != 1:
        raise ValueError("文件带有特殊属性或硬链接，跨卷复制无法保真，请人工处理")
    getinfo = kernel.GetFileInformationByHandleEx
    getinfo.argtypes = (wintypes.HANDLE, ctypes.c_int, wintypes.LPVOID, wintypes.DWORD)
    getinfo.restype = wintypes.BOOL
    buffer = ctypes.create_string_buffer(65536)
    if not getinfo(handle, 7, buffer, len(buffer)):
        raise ValueError("无法验证文件数据流，已保留源文件")
    following, length = struct.unpack_from("<II", buffer)
    if following or bytes(buffer[24:24+length]).decode("utf-16-le") != "::$DATA":
        raise ValueError("文件含附加 NTFS 数据流，跨卷复制无法保真，已保留源文件")
    _check_extended_attributes(handle)


class _IoStatus(ctypes.Structure):
    _fields_ = [("status", ctypes.c_void_p), ("information", ctypes.c_size_t)]


def _check_extended_attributes(handle):
    # Kernel-managed Smart App Control stamps are generated by Windows on both
    # volumes. Do not discard application-defined EAs (including WSL metadata).
    query = ctypes.WinDLL("ntdll").NtQueryEaFile
    query.argtypes = (wintypes.HANDLE, ctypes.POINTER(_IoStatus), wintypes.LPVOID,
                      wintypes.DWORD, ctypes.c_ubyte, wintypes.LPVOID, wintypes.DWORD,
                      wintypes.LPVOID, ctypes.c_ubyte)
    query.restype = wintypes.LONG
    buffer = ctypes.create_string_buffer(65536)
    io = _IoStatus()
    status = query(handle, ctypes.byref(io), buffer, len(buffer), 0, None, 0, None, 1) & 0xffffffff
    if status in (0xC000004F, 0xC0000052, 0x80000012):  # No EAs or unsupported on this volume.
        return
    if status != 0:
        raise ValueError("无法验证扩展属性，已保留源文件")
    offset = 0
    while offset < io.information:
        following, _, length, _ = struct.unpack_from("<IBBH", buffer, offset)
        name = bytes(buffer[offset+8:offset+8+length]).upper()
        if name not in (b"$KERNEL.SMARTLOCKER.ORIGINCLAIM", b"$KERNEL.PURGE.SMARTLOCKER.VALID"):
            raise ValueError("文件带有额外扩展属性，跨卷复制无法保真，已保留源文件")
        if not following:
            return
        offset += following


def copy_times(source_handle, target_handle):
    times = [wintypes.FILETIME() for _ in range(3)]
    pointers = [ctypes.byref(value) for value in times]
    signature = (wintypes.HANDLE,) + (ctypes.POINTER(wintypes.FILETIME),) * 3
    getter, setter = kernel.GetFileTime, kernel.SetFileTime
    getter.argtypes = setter.argtypes = signature
    if not getter(source_handle, *pointers) or not setter(target_handle, *pointers):
        raise ctypes.WinError(ctypes.get_last_error())


def remove_checked_handle(handle):
    # FileDispositionInfo marks this exact open file for removal at close.
    delete = wintypes.BOOL(True)
    if not set_information(handle, 4, ctypes.byref(delete), ctypes.sizeof(delete)):
        raise ctypes.WinError(ctypes.get_last_error())


def case_sensitive_directory(path):
    handle = open_entry(path, READ_ATTRIBUTES)
    try:
        flags = wintypes.DWORD()
        info = kernel.GetFileInformationByHandleEx
        info.argtypes = (wintypes.HANDLE, ctypes.c_int, wintypes.LPVOID, wintypes.DWORD)
        if info(handle, 23, ctypes.byref(flags), ctypes.sizeof(flags)):
            return bool(flags.value & 1)
        if ctypes.get_last_error() not in (1, 50, 87, 124):
            raise ctypes.WinError(ctypes.get_last_error())
        return False
    finally:
        close_handle(handle)


class RenameInfo(ctypes.Structure):
    _fields_ = [("replace", wintypes.DWORD), ("parent", wintypes.HANDLE),
                ("name_length", wintypes.DWORD), ("name", wintypes.WCHAR * 1)]


def rename_without_replace(handle: int, target: Path):
    # FileRenameInfo operates on this specific source handle. ReplaceIfExists
    # stays FALSE and Windows checks destination occupancy inside the rename.
    name = extended_path(target).encode("utf-16-le")
    size = max(ctypes.sizeof(RenameInfo), RenameInfo.name.offset + len(name) + 2)
    buffer = ctypes.create_string_buffer(size)
    info = RenameInfo.from_buffer(buffer)
    info.name_length = len(name)
    ctypes.memmove(ctypes.addressof(buffer) + RenameInfo.name.offset, name, len(name))
    if not set_information(handle, 3, buffer, size):
        raise ctypes.WinError(ctypes.get_last_error())
